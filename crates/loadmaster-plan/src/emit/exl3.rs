//! tabbyAPI (ExLlamaV3) `config.yml`, model section.

use std::path::Path;

use crate::{ConfigFile, KvType, Plan};

/// tabbyAPI is started from its checkout with the generated config.
pub fn argv() -> Vec<String> {
    ["python3", "main.py", "--config", "config.yml"]
        .map(String::from)
        .to_vec()
}

/// tabbyAPI `cache_mode`.
pub fn cache_mode(kv: KvType) -> &'static str {
    match kv {
        KvType::F16 | KvType::Fp8 => "FP16",
        KvType::Q8_0 => "Q8",
        KvType::Q4_0 => "Q4",
    }
}

pub fn config(plan: &Plan) -> ConfigFile {
    let path = Path::new(&plan.model.path);
    let dir = path
        .parent()
        .map_or(".".into(), |p| p.display().to_string());
    let name = path.file_name().map_or_else(
        || plan.model.path.clone(),
        |n| n.to_string_lossy().into_owned(),
    );
    let contents = format!(
        "# tabbyAPI config.yml, model section, generated by loadmaster\n\
         model:\n  model_dir: {}\n  model_name: {}\n  max_seq_len: {}\n  cache_size: {}\n  cache_mode: {}\n  gpu_split_auto: true\n  chunk_size: {}\n",
        yaml_str(&dir),
        yaml_str(&name),
        plan.ctx,
        plan.ctx,
        cache_mode(plan.kv),
        plan.n_ubatch,
    );
    ConfigFile {
        name: "config.yml".into(),
        contents,
    }
}

/// Quote a YAML scalar when it is not plainly safe.
fn yaml_str(s: &str) -> String {
    let plain = !s.is_empty()
        && s.bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"_-./".contains(&b));
    if plain {
        s.to_owned()
    } else {
        format!("'{}'", s.replace('\'', "''"))
    }
}
